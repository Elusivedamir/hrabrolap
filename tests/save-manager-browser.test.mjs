import {before,after,test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
import {freshProgress} from '../game-core.mjs';
import {CURRENT_SAVE_KEY,makeBackup} from '../save-backup.mjs';
const base=process.env.HRABROLAP_BASE_URL||'http://127.0.0.1:8080/';
let browser;
before(async()=>{await fs.mkdir('qa/screenshots',{recursive:true});browser=await chromium.launch({headless:true,...(process.env.HRABROLAP_CHROMIUM_EXECUTABLE?{executablePath:process.env.HRABROLAP_CHROMIUM_EXECUTABLE,args:['--no-zygote','--disable-gpu']}:{})});});
after(async()=>{await browser?.close();});
test('P0 mobile save manager exports and imports without altering game until confirmation',async()=>{
 const original=freshProgress();original.gold=23450;original.room=352;original.best=351;original.achievementClaimed=[0,3];original.megaBossWins=[50,100,150,200,250,300,350];
 const first=await browser.newContext({viewport:{width:360,height:740},isMobile:true,hasTouch:true,acceptDownloads:true});
 const page=await first.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(({key,value})=>localStorage.setItem(key,JSON.stringify(value)),{key:CURRENT_SAVE_KEY,value:original});
 await page.goto(new URL('save-manager.html',base).href);
 assert.equal(await page.locator('#export').isEnabled(),true);
 await page.screenshot({path:'qa/screenshots/p0-save-backup-mobile.png'});
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
 assert.match(download.suggestedFilename(),/hrabrolap-save-wave-351\.json/);
 const file=await fs.readFile(await download.path(),'utf8');
 assert.match(file,/"hrabrolap-save-backup"/);
 const second=await browser.newContext({viewport:{width:360,height:740},isMobile:true,hasTouch:true});
 const restored=await second.newPage();restored.on('pageerror',e=>errors.push(e.message));
 await restored.goto(new URL('save-manager.html',base).href);
 assert.equal(await restored.locator('#export').isEnabled(),false);
 await restored.locator('#file').setInputFiles({name:'copy.json',mimeType:'application/json',buffer:Buffer.from(file)});
 assert.match(await restored.locator('#preview').textContent(),/351 из 2000/);
 assert.equal(await restored.locator('#import').isEnabled(),true);
 assert.equal(await restored.evaluate(k=>localStorage.getItem(k),CURRENT_SAVE_KEY),null,'no write prior to user approval');
 restored.once('dialog',dialog=>dialog.accept());
 await restored.locator('#import').click();
 const data=await restored.evaluate(k=>JSON.parse(localStorage.getItem(k)),CURRENT_SAVE_KEY);
 assert.equal(data.gold,23450);assert.equal(data.room,352);
 assert.deepEqual(data.achievementClaimed,[0,3]);assert.deepEqual(data.megaBossWins,original.megaBossWins);
 await restored.screenshot({path:'qa/screenshots/p0-save-restore-mobile.png'});
 assert.deepEqual(errors,[]);
 await first.close();await second.close();
});
test('P0 rejecting invalid file does not overwrite current save',async()=>{
 const ctx=await browser.newContext();const page=await ctx.newPage();
 const original=freshProgress();original.best=10;original.room=11;original.gold=300;
 await page.addInitScript(({k,v})=>localStorage.setItem(k,JSON.stringify(v)),{k:CURRENT_SAVE_KEY,v:original});
 await page.goto(new URL('save-manager.html',base).href);
 await page.locator('#file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"version":999}')});
 assert.equal(await page.locator('#import').isEnabled(),false);
 assert.equal((await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),CURRENT_SAVE_KEY)).gold,300);
 await ctx.close();
});
