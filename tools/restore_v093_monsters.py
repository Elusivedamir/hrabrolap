#!/usr/bin/env python3
"""Restore EXACT v0.9.3 monster SVG frames from compact archived templates.

Every generated byte sequence is SHA-256 checked against the archived ZIP.
Inputs are byte-locked art/monsters-v2/*.svg and art/approved/crown.svg.
Never replace approved bodies with legacy model drawings.
"""
from pathlib import Path
import base64, hashlib, json, re, zlib

ROOT=Path(__file__).resolve().parents[1]
PACK=ROOT/'assets/legacy-v093-monster-frames.manifest.b64'
ANIM=ROOT/'animations'
FRAMES=json.loads(zlib.decompress(base64.b64decode(PACK.read_text().strip())))
MONSTERS={'slime','spider','mouse','mushroom','beetle','larva','bat','ghost'}
crown=base64.b64encode((ROOT/'art/approved/crown.svg').read_bytes()).decode()
assert len(FRAMES)==192, f'Expected exactly 192 frames, got {len(FRAMES)}'
for path,data in sorted(FRAMES.items()):
    parts=path.split('/')
    assert len(parts)==5 and parts[0]=='animations' and parts[1] in MONSTERS
    assert parts[2] in ('normal','boss') and parts[3] in ('attack','hurt')
    assert re.fullmatch(r'(0[1-6])\.svg',parts[4])
    body=base64.b64encode((ROOT/'art/monsters-v2'/f'{parts[1]}.svg').read_bytes()).decode()
    render=data['template'].replace('__MODEL__',body).replace('__CROWN__',crown).encode()
    actual=hashlib.sha256(render).hexdigest()
    assert actual==data['sha256'], f'Archived sprite has diverged: {path}'
    output=ROOT/path
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_bytes(render)
print('RESTORED 192 exact approved v0.9.3 SVG monster frames (8 species × normal/boss × attack/hurt × 6)')
